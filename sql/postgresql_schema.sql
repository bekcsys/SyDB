-- Sauna QC tracking schema (reference DDL).
-- Django migrations are the source of truth for the running application.
-- PostgreSQL ENUMs are not used: Django TextChoices + CHECK constraints
-- are easier to migrate. updated_at is owned by Django auto_now, not a trigger.
-- PositiveIntegerField also adds a ">= 0" check; Meta checks are stricter.

-- Cardinality:
--   control_panels 1 -- * power_boxes        (control panel optional)
--   power_boxes 1 -- * products              (each product has one power box)
-- SmartMak products use SmMak_v1.0.
-- Item numbers: 310103-01C, 310103-02C, 310104-02, 310103-03C, 310103-04C, 310103-06C.
-- products.item_no is not unique. product_id identifies each product.
-- The same item number can belong to more than one product when the power box differs.
-- A product has one power box, and that power box has one control panel.
--   products 1 -- * product_items
-- product_items store one serial and its QC tester, status, form, and note.
-- Several serials can share one product_id. serial_no stays unique.
-- product_id may be null only when an existing serial has no recoverable product.
--   products * -- * product_issues through product_issue_products
-- One issue can apply to many products. Status is Not Started, In Progress, or Solved.
-- Solved issues stay in the table.
-- doc_ref names an existing control-panel instruction or power-box firmware file.
-- documentation and documentation_name hold an older uploaded copy, when one exists.

-- FK policy matches model on_delete. Django stores these foreign keys as
-- DEFERRABLE INITIALLY DEFERRED and applies the policy in the ORM.
--   PROTECT: product, power box, and control panel FKs
--   CASCADE: product_issue_products rows are removed with the issue or product
-- power_boxes.note is an optional written note.
-- control_panels.firmware_device names the panel's firmware device.
-- power_boxes.firmware_info names the box firmware device.
-- A power box keeps one picture, plus one firmware document and one firmware video.
-- product_items.qc_form is the QC form PDF. note is the QC note.

BEGIN;

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_no VARCHAR(64) NOT NULL,
    product_name VARCHAR(128) NOT NULL,
    voltage INTEGER NOT NULL,
    wattage INTEGER NOT NULL,
    supplier VARCHAR(64) NOT NULL,
    number_of_cords INTEGER NOT NULL DEFAULT 1,
    plug_type VARCHAR(32) NOT NULL DEFAULT '',
    watt_on_label INTEGER NULL,
    power_box_id BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT products_voltage_check CHECK (voltage >= 0),
    CONSTRAINT products_voltage_positive CHECK (voltage > 0),
    CONSTRAINT products_wattage_check CHECK (wattage >= 0),
    CONSTRAINT products_wattage_positive CHECK (wattage > 0),
    CONSTRAINT products_number_of_cords_check CHECK (number_of_cords >= 0),
    CONSTRAINT products_number_of_cords_min_1 CHECK (number_of_cords >= 1),
    CONSTRAINT products_plug_type_valid CHECK (plug_type IN ('', 'NEMA 5-20P', 'L6-20P')),
    CONSTRAINT products_watt_on_label_check CHECK (watt_on_label >= 0),
    CONSTRAINT products_watt_on_label_positive CHECK (watt_on_label IS NULL OR watt_on_label > 0)
);

CREATE TABLE control_panels (
    control_panel_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    part_number VARCHAR(64) NOT NULL DEFAULT '',
    picture BYTEA NULL,
    picture_name VARCHAR(255) NOT NULL DEFAULT '',
    documentation_1 BYTEA NULL,
    documentation_1_name VARCHAR(255) NOT NULL DEFAULT '',
    documentation_2 BYTEA NULL,
    documentation_2_name VARCHAR(255) NOT NULL DEFAULT '',
    firmware_device VARCHAR(128) NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT control_panels_name_key UNIQUE (name)
);

CREATE TABLE power_boxes (
    power_box_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    part_number VARCHAR(64) NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    control_panel_id BIGINT NULL,
    picture BYTEA NULL,
    picture_name VARCHAR(255) NOT NULL DEFAULT '',
    firmware_info VARCHAR(128) NOT NULL DEFAULT '',
    firmware_document BYTEA NULL,
    firmware_document_name VARCHAR(255) NOT NULL DEFAULT '',
    firmware_video BYTEA NULL,
    firmware_video_name VARCHAR(255) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT power_boxes_name_key UNIQUE (name),
    CONSTRAINT power_boxes_control_panel_id_fk
        FOREIGN KEY (control_panel_id) REFERENCES control_panels (control_panel_id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE INDEX power_boxes_control_panel_id_idx ON power_boxes (control_panel_id);

-- Luis_v1.0 firmware_info is ACD 2. Luis_v1.1 firmware_info is ACD 3.

ALTER TABLE products
    ADD CONSTRAINT products_power_box_id_fk
        FOREIGN KEY (power_box_id) REFERENCES power_boxes (power_box_id)
        ON DELETE RESTRICT ON UPDATE CASCADE;

CREATE INDEX products_power_box_id_idx ON products (power_box_id);

CREATE TABLE product_items (
    product_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NULL,
    serial_no VARCHAR(64) NOT NULL,
    qc_tester_name VARCHAR(64) NOT NULL DEFAULT '',
    qc_status VARCHAR(32) NOT NULL DEFAULT 'ASSIGNED',
    qc_form BYTEA NULL,
    qc_form_name VARCHAR(255) NOT NULL DEFAULT '',
    note TEXT NOT NULL DEFAULT '',
    CONSTRAINT product_items_serial_no_key UNIQUE (serial_no),
    CONSTRAINT product_items_product_id_fk
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT product_items_qc_status_valid CHECK (
        qc_status IN (
            'ASSIGNED', 'TESTING', 'QC_PASSED', 'QC_FAILED', 'ON_HOLD'
        )
    )
);

CREATE INDEX product_items_product_id_idx ON product_items (product_id);
CREATE INDEX idx_product_items_qc_status ON product_items (qc_status);

CREATE TABLE product_issues (
    product_issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date DATE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'NOT_STARTED',
    note TEXT NOT NULL DEFAULT '',
    doc_ref VARCHAR(80) NOT NULL DEFAULT '',
    documentation BYTEA NULL,
    documentation_name VARCHAR(255) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT product_issues_status_valid CHECK (
        status IN ('NOT_STARTED', 'IN_PROGRESS', 'SOLVED')
    )
);

CREATE INDEX idx_product_issues_date ON product_issues (date DESC);

CREATE TABLE product_issue_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    productissue_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    CONSTRAINT product_issue_products_issue_product_uniq UNIQUE (productissue_id, product_id),
    CONSTRAINT product_issue_products_issue_fk
        FOREIGN KEY (productissue_id) REFERENCES product_issues (product_issue_id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT product_issue_products_product_fk
        FOREIGN KEY (product_id) REFERENCES products (product_id)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX product_issue_products_productissue_id_idx ON product_issue_products (productissue_id);
CREATE INDEX product_issue_products_product_id_idx ON product_issue_products (product_id);

COMMIT;
